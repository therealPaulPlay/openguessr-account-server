import { ApiKeysClient } from '@google-cloud/apikeys';

// Direct path to the service account key file
const keyPath = "./openguessr-429713-beb2e39c60d5.json";

// Instantiate the client with the credentials
const client = new ApiKeysClient.v2({ keyFilename: keyPath });

const PROJECT_ID = 'openguessr-429713';
const PARENT = `projects/${PROJECT_ID}/locations/global`;

// Configuration for referrers
const REFERRERS = [
  'https://openguessr.com',
  'https://*.openguessr.com/*',
  'og-venatus-test.netlify.app',
  'https://openguessr-86h.pages.dev',
  '*.openguessr-86h.pages.dev/*',
  'localhost:3000'
];

// API Target for Google Maps JavaScript API
const API_TARGETS = [
  {
    service: 'maps-backend.googleapis.com',
    methods: []
  }
];

// Store the current API key and its ID
let currentApiKey = null;
let currentApiKeyId = null;
let currentApiKeyString = null;

// Store the future API keys and their IDs
let futureApiKeys = [];
const INITIAL_KEY_WAIT_TIME = 90 * 60 * 1000; // 1.5 hours
const KEY_ROTATION_INTERVAL = 15 * 60 * 1000; // 10 minutes

const uniqueServerNr = Math.floor(1000 * Math.random());

// Function to format date and time
function formatDate(date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  const hours = String(date.getHours()).padStart(2, '0');
  const minutes = String(date.getMinutes()).padStart(2, '0');
  return `${year}-${month}-${day}_${hours}-${minutes}`;
}

// Function to find a backup key if it exists
async function findBackupKey() {
  try {
    const [keys] = await client.listKeys({ parent: PARENT });
    const backupKey = keys.find(key =>
      key.displayName.toLowerCase().includes('backup')
    );
    return backupKey;
  } catch (error) {
    console.error('Error finding backup key:', error.message || error);
    return null;
  }
}

// Create a new API key with specified referrers and API restrictions
async function createApiKey() {
  try {
    const dateTime = formatDate(new Date());
    const displayName = `Auto-Generated JS Maps API Key ${dateTime} Server-Nr: ${uniqueServerNr}`;

    const request = {
      parent: PARENT,
      key: {
        displayName: displayName,
        restrictions: {
          browserKeyRestrictions: {
            allowedReferrers: REFERRERS
          },
          apiTargets: API_TARGETS
        }
      }
    };

    const [operation] = await client.createKey(request);
    const [response] = await operation.promise();

    console.log('Created Key:', response);
    return response;
  } catch (error) {
    console.error('Error creating API key:', error.message || error);
    return null;
  }
}

// Delete an API key by ID
async function deleteApiKey(keyId) {
  try {
    const request = {
      name: `projects/${PROJECT_ID}/locations/global/keys/${keyId}`
    };

    const [operation] = await client.deleteKey(request);
    await operation.promise();

    console.log('Deleted Key:', keyId);
  } catch (error) {
    console.error('Error deleting API key:', error.message || error);
  }
}

// Get the API key string
async function getApiKeyString(keyId) {
  try {
    const request = {
      name: `projects/${PROJECT_ID}/locations/global/keys/${keyId}`
    };

    const [response] = await client.getKeyString(request);
    console.log('API Key String:', response);
    return response;
  } catch (error) {
    console.error('Error getting API key string:', error.message || error);
    return null;
  }
}

// Convert Timestamp to JavaScript Date
function timestampToDate(timestamp) {
  // Convert seconds to a number
  const seconds = Number(timestamp.seconds); // Convert string to number
  const nanoseconds = timestamp.nanos;

  // Convert to milliseconds
  const milliseconds = seconds * 1000 + nanoseconds / 1e6;

  // Create and return the Date object
  const date = new Date(milliseconds);
  console.log(`Converted Timestamp to Date: ${date.toISOString()}`);
  return date;
}

// Delete old "Auto-Generated" keys older than 10 minutes
async function deleteOldAutoGeneratedKeys() {
  try {
    const [keys] = await client.listKeys({ parent: PARENT });
    const tenMinutesAgo = new Date(Date.now() - 10 * 60 * 1000);

    console.log(`Current time: ${new Date().toISOString()}`);
    console.log(`Cutoff time for old keys: ${tenMinutesAgo.toISOString()}`);

    const oldKeys = keys.filter(key => {
      const createTime = timestampToDate(key.createTime);
      return key.displayName.toLowerCase().includes('auto-generated') &&
        createTime < tenMinutesAgo;
    });

    console.log(`Keys to be deleted: ${oldKeys.map(key => key.uid).join(', ')}`);

    for (const key of oldKeys) {
      await deleteApiKey(key.uid);
    }
  } catch (error) {
    console.error('Error deleting old Auto-Generated keys:', error.message || error);
  }
}

// Initialize the API keys and start the key cycle
let keySystemInitialized = false;
let usingBackupKey = false;

async function initializeKeys() {
  if (keySystemInitialized) return;

  try {
    // Check for existing backup key
    const backupKey = await findBackupKey();
    if (backupKey) {
      console.log('Found Backup Key:', backupKey.displayName);
      currentApiKey = backupKey;
      currentApiKeyId = backupKey.uid;
      currentApiKeyString = await getApiKeyString(currentApiKeyId);
      if (!currentApiKeyString) throw new Error('Failed to get backup API key string');
      usingBackupKey = true;
    } else {
      // No backup key found, create a new API key
      currentApiKey = await createApiKey();
      if (!currentApiKey) throw new Error('Failed to create initial API key');
      currentApiKeyId = currentApiKey.uid;
      currentApiKeyString = await getApiKeyString(currentApiKeyId);
      if (!currentApiKeyString) throw new Error('Failed to get API key string');
    }

    // Delete old Auto-Generated keys
    await deleteOldAutoGeneratedKeys();

    // Pre-create future API keys
    await updateFutureKeys();

    // Start the key cycle
    startKeyCycle();

    keySystemInitialized = true;
  } catch (error) {
    console.error('Error initializing keys:', error.message || error);
  }
}

// Function to get the current API key
async function getApiKey() {
  try {
    return currentApiKeyString;
  } catch (error) {
    console.error('Error getting API key:', error.message || error);
    return null;
  }
}

// Update future keys and manage rotation
async function updateFutureKeys() {
  try {
    // Calculate the number of future keys needed
    const keysNeeded = Math.ceil(INITIAL_KEY_WAIT_TIME / KEY_ROTATION_INTERVAL);

    // Filter out the valid future keys (select those old enough to be used)
    const validFutureKeys = futureApiKeys.filter(key => new Date() - new Date(key.createdAt) >= INITIAL_KEY_WAIT_TIME);

    // Create new future keys if necessary
    const additionalKeysNeeded = keysNeeded - validFutureKeys.length;
    for (let i = 0; i < additionalKeysNeeded; i++) {
      const newFutureKey = await createApiKey();
      if (newFutureKey) {
        const newKeyString = await getApiKeyString(newFutureKey.uid);
        if (newKeyString) {
          futureApiKeys.push({
            id: newFutureKey.uid,
            string: newKeyString,
            createdAt: new Date()
          });
        }
      }
    }
  } catch (error) {
    console.error('Error updating future keys:', error.message || error);
  }
}

// Rotate keys every 30 minutes
function startKeyCycle() {
  setInterval(async () => {
    try {
      console.log("New key cycle running...");

      // Ensure we have at least one valid future key
      const validFutureKeys = futureApiKeys.filter(key => new Date() - new Date(key.createdAt) >= INITIAL_KEY_WAIT_TIME);
      if (validFutureKeys.length === 0) {
        console.log("Exiting new key cycle as no valid (old enough) keys exist.");
        return;
      }

      // Store the old current key ID before updating it
      const oldCurrentApiKeyId = currentApiKeyId;

      // Make the oldest valid future key the current key
      const oldestFutureKey = validFutureKeys[0];
      currentApiKey = {
        id: oldestFutureKey.id,
        string: oldestFutureKey.string
      };
      currentApiKeyId = oldestFutureKey.id;
      currentApiKeyString = oldestFutureKey.string;

      // Remove the used key from the future keys list
      futureApiKeys = futureApiKeys.filter(key => key.id !== currentApiKeyId);

      console.log("Switched to a new current key successfully. New key: " + currentApiKeyString.keyString + " at " + formatDate(new Date()));

      // Delete old current key after 2 minutes of inactivity
      setTimeout(async () => {
        if (oldCurrentApiKeyId) {
          if (!usingBackupKey) {
            await deleteApiKey(oldCurrentApiKeyId);
          } else {
            usingBackupKey = false;
          }
        }
      }, 2 * 60 * 1000);

      // Update future keys to ensure we have enough valid future keys
      await updateFutureKeys();

    } catch (error) {
      console.error('Error in key cycle:', error.message || error);
    }
  }, KEY_ROTATION_INTERVAL);
}

